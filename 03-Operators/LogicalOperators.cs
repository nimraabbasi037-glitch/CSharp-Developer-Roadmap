// =======================
// Logical Operators
// =======================

bool isStudent = true;
bool hasFeePaid = false;

Console.WriteLine("AND (&&) Operator");
Console.WriteLine(isStudent && hasFeePaid);

Console.WriteLine("OR (||) Operator");
Console.WriteLine(isStudent || hasFeePaid);

Console.WriteLine("NOT (!) Operator");
Console.WriteLine(!isStudent);
Console.WriteLine(!hasFeePaid);
