// =======================
// Bitwise Operators
// =======================

int a = 5;
int b = 3;

Console.WriteLine("Bitwise AND (&): " + (a & b));

Console.WriteLine("Bitwise OR (|): " + (a | b));

Console.WriteLine("Bitwise XOR (^): " + (a ^ b));

Console.WriteLine("Bitwise NOT (~): " + (~a));

Console.WriteLine("Left Shift (<<): " + (a << 1));

Console.WriteLine("Right Shift (>>): " + (a >> 1));
