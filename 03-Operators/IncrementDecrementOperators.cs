// =======================
// Increment and Decrement Operators
// =======================

int number = 10;

Console.WriteLine("Initial Value : " + number);

number++;
Console.WriteLine("After Increment : " + number);

number++;
Console.WriteLine("After Increment Again : " + number);

number--;
Console.WriteLine("After Decrement : " + number);

number--;
Console.WriteLine("After Decrement Again : " + number);
